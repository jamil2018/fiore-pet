# Worktree bootstrap for Fiore (Windows). Invoked by .cursor/worktrees.json in the new worktree root.
#   1. npm ci                      (deterministic install; falls back to npm install without a lockfile)
#   2. sccache                     (shared compile cache so a cold Tauri build is not repeated per worktree)
#   3. per-worktree CARGO_TARGET_DIR (separate cargo build locks, so parallel builds do not serialize)
#   4. local harness dirs          (.harness/*, evals/results, logs are gitignored and absent in fresh worktrees)
# Cargo settings are persisted in <worktree>\.cargo\config.toml (hidden via .git/info/exclude) because
# environment variables set here do not reach later agent shells.
# Secrets are never copied: CURSOR_API_KEY is read from the environment only; .env files are not propagated.
# Options: -Force (also configure cargo in the main checkout), -SkipInstall (skip npm).
# Env:     FIORE_TARGET_ROOT = base dir for per-worktree target dirs (default: <worktree>\target).
[CmdletBinding()]
param(
    [switch]$Force,
    [switch]$SkipInstall
)

$ErrorActionPreference = 'Stop'

function Write-Step($msg) { Write-Host "[setup-worktree] $msg" }

# Native stderr must not become a terminating error under 'Stop' (e.g. git probes outside a repo).
$PSNativeCommandUseErrorActionPreference = $false
$root = (git rev-parse --show-toplevel 2>$null)
if (-not $root) { $root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path }
$root = (Resolve-Path $root).Path
Set-Location $root

# Linked worktree = git dir differs from the common git dir.
$gitDir = (git rev-parse --absolute-git-dir 2>$null)
$commonDir = (git rev-parse --path-format=absolute --git-common-dir 2>$null)
$isLinkedWorktree = $gitDir -and $commonDir -and ((Resolve-Path $gitDir).Path -ne (Resolve-Path $commonDir).Path)
Write-Step "root=$root linkedWorktree=$isLinkedWorktree"

# --- 1. Local harness directories -------------------------------------------------------------
foreach ($d in '.harness/runs', '.harness/metrics', '.harness/claims', '.harness/handoff', 'evals/results', 'logs') {
    New-Item -ItemType Directory -Force -Path (Join-Path $root $d) | Out-Null
}

# --- 2. npm ------------------------------------------------------------------------------------
if (-not $SkipInstall -and (Test-Path (Join-Path $root 'package.json'))) {
    if (-not (Get-Command npm -ErrorAction SilentlyContinue)) { throw 'npm not found on PATH (install Node >= 20).' }
    if (Test-Path (Join-Path $root 'package-lock.json')) {
        Write-Step 'npm ci'
        npm ci --no-audit --no-fund
    } else {
        Write-Step 'package-lock.json missing; npm install'
        npm install --no-audit --no-fund
    }
    if ($LASTEXITCODE -ne 0) { throw "npm install step failed (exit $LASTEXITCODE)." }
} else {
    Write-Step 'skipping npm (no package.json or -SkipInstall)'
}

# --- 3. Rust: sccache + per-worktree target dir -----------------------------------------------
$hasRust = (Test-Path (Join-Path $root 'src-tauri/Cargo.toml')) -or (Test-Path (Join-Path $root 'Cargo.toml'))
if (-not $hasRust) {
    Write-Step 'no Cargo.toml yet; skipping cargo configuration'
} elseif (-not ($isLinkedWorktree -or $Force)) {
    Write-Step 'main checkout; skipping cargo configuration (use -Force to apply)'
} else {
    $sccache = Get-Command sccache -ErrorAction SilentlyContinue
    if ($sccache) {
        Write-Step "sccache: $($sccache.Source)"
        try { sccache --start-server 2>&1 | Out-Null } catch { }
    } else {
        Write-Warning 'sccache not found; builds will not share compiled dependencies. Install: winget install Mozilla.sccache  (or: cargo install sccache --locked)'
    }

    $name = Split-Path $root -Leaf
    $targetBase = if ($env:FIORE_TARGET_ROOT) { Join-Path $env:FIORE_TARGET_ROOT $name } else { Join-Path $root 'target' }
    New-Item -ItemType Directory -Force -Path $targetBase | Out-Null
    $targetToml = ($targetBase -replace '\\', '/')

    $cargoDir = Join-Path $root '.cargo'
    $cargoCfg = Join-Path $cargoDir 'config.toml'
    $tracked = (git ls-files ".cargo/config.toml")
    if ($tracked) {
        Write-Warning '.cargo/config.toml is tracked; not overwriting. Set CARGO_TARGET_DIR / RUSTC_WRAPPER manually.'
    } else {
        New-Item -ItemType Directory -Force -Path $cargoDir | Out-Null
        $lines = @(
            '# Generated by scripts/setup-worktree-windows.ps1 (local only, excluded from git).',
            '[build]',
            "target-dir = `"$targetToml`""
        )
        if ($sccache) {
            $lines += "rustc-wrapper = `"$(($sccache.Source) -replace '\\', '/')`""
            $lines += 'incremental = false'
        }
        Set-Content -Path $cargoCfg -Value ($lines -join "`n") -Encoding utf8

        # Hide the generated file from git without touching the tracked .gitignore.
        $exclude = (git rev-parse --path-format=absolute --git-path info/exclude 2>$null)
        if ($exclude) {
            New-Item -ItemType Directory -Force -Path (Split-Path $exclude) | Out-Null
            if (-not (Test-Path $exclude) -or -not (Select-String -Path $exclude -SimpleMatch '/.cargo/config.toml' -Quiet)) {
                Add-Content -Path $exclude -Value '/.cargo/config.toml'
            }
        }
        Write-Step "wrote $cargoCfg (target-dir=$targetToml)"
    }
}

Write-Host '[setup-worktree] done'
